/**
 * 金额格式化。消费页和首页的卡片共用这一处。
 *
 * 与 `date.ts` 是同一个理由：同一个数字在两处各格式化一遍，
 * 迟早会出现首页写"¥1,234.5"、消费页写"¥1,234.50"。两者都"对"，
 * 所以没人会当成 bug —— 这种不一致最难发现。
 *
 * 没有做成金额运算工具：**本项目的汇总一律由后端算**（见 docs/接口清单.md §9），
 * 前端只负责显示。哪天这里需要加 `add()` / `sum()`，先回去看看是不是把
 * 本该后端做的事搬到了前端。
 */

/**
 * `1234.5` → `"1,234.50"`（不含货币符号，符号由调用方按语境加）。
 *
 * 固定两位小数：金额的两位是**格**不是精度，`¥12.3` 看着像漏了一位。
 *
 * 整数部分加千分位不是装饰 —— 五位数以上不加分隔符，一眼扫过去很难看出量级。
 *
 * 用 `toFixed` 而不是 `toLocaleString`：后者受运行环境的区域数据影响，
 * 同一份代码在不同机器、不同浏览器上可能给出不同的分隔符。
 *
 * 全程只在**字符串**上做切分和拼接：`noUncheckedIndexedAccess` 下，
 * `split('.')` 的解构会得到 `string | undefined`，而且浮点数本来就不该
 * 再参与这里的运算 —— 该算的在服务端已经用 BigDecimal 算完了。
 */
export function money(value: number): string {
  const text = value.toFixed(2)
  const dot = text.indexOf('.')
  return `${text.slice(0, dot).replace(/\B(?=(\d{3})+(?!\d))/g, ',')}${text.slice(dot)}`
}
